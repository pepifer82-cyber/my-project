create table public.printer_manual_counter_entries (
  id bigint generated by default as identity primary key,
  project_id uuid not null references public.control_projects(id) on delete cascade,
  printer_id uuid not null references public.monitored_printers(id) on delete cascade,
  page_count bigint not null check (page_count >= 0),
  scanner_count bigint check (scanner_count is null or scanner_count >= 0),
  recorded_at timestamptz not null default now(),
  note text,
  created_by uuid not null default auth.uid() references auth.users(id),
  created_at timestamptz not null default now(),
  constraint printer_manual_counter_entries_note_length
    check (note is null or char_length(note) <= 1000)
);

create index printer_manual_counter_entries_lookup_idx
  on public.printer_manual_counter_entries (project_id, printer_id, recorded_at desc, id desc);

alter table public.printer_manual_counter_entries enable row level security;

create policy printer_manual_counter_entries_member_select
  on public.printer_manual_counter_entries
  for select
  to authenticated
  using (private.control_is_member(project_id));

create policy printer_manual_counter_entries_member_insert
  on public.printer_manual_counter_entries
  for insert
  to authenticated
  with check (
    private.control_is_member(project_id)
    and created_by = (select auth.uid())
    and exists (
      select 1
      from public.monitored_printers mp
      where mp.id = printer_manual_counter_entries.printer_id
        and mp.project_id = printer_manual_counter_entries.project_id
    )
  );

-- Supabase Data API exposure is explicit for this new public table.
grant select, insert on public.printer_manual_counter_entries to authenticated;
grant usage, select on sequence public.printer_manual_counter_entries_id_seq to authenticated;

comment on table public.printer_manual_counter_entries is
  'Manual meter entries from each printer detail page. Kept separate from the agent automatic readings.';
